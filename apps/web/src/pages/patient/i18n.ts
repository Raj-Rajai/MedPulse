const PHRASES = Object.entries(GU.phrase).sort((a, b) => b[0].length - a[0].length);

function preserveOuter(original: string, translated: string): string {
    const start = (original.match(/^\s*/) as RegExpMatchArray)[0];
    const end = (original.match(/\s*$/) as RegExpMatchArray)[0];
    return start + translated + end;
}

export function translateText(text: string, lang: Lang): string {
    if (lang !== 'gu' || !text || !text.trim()) return text;
    const trimmed = text.trim();
    if (GU.exact[trimmed]) return preserveOuter(text, GU.exact[trimmed]);
    let out = text;
    PHRASES.forEach(([en, gu]) => {
        out = out.split(en).join(gu);
    });
    return out;
}

export type Translate = (text: string | number | null | undefined) => string;

export const makeT = (lang: Lang): Translate => (text) => translateText(String(text ?? ''), lang);

export const LangContext = createContext<Translate>(makeT('en'));

export const useT = (): Translate => useContext(LangContext);

export function storedLang(): Lang {
    try { return localStorage.getItem('medpulse_patient_lang') === 'gu' ? 'gu' : 'en'; } catch { return 'en'; }
}

export function storeLang(lang: Lang): void {
    try { localStorage.setItem('medpulse_patient_lang', lang); } catch { /* ignore */ }
}
